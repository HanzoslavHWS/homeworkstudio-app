import { NextResponse, type NextRequest } from "next/server.js";
import { isAppRole, type AppRole } from "../../domain/accessControl.ts";
import { SupabaseConfigurationError } from "../db/supabase.server.ts";
import { AuthSchemaNotMigratedError } from "./authStore.server.ts";
import { authorize } from "./requestAuth.ts";
import { AppBaseUrlError, AuthGatewayError, appBaseUrl, authGateway, normalizeEmail } from "./supabaseAuth.server.ts";
import { LastActiveAdminError, UserConflictError, usersAdminStore, type AdminUserRecord } from "./usersAdmin.supabase.ts";

/**
 * Administrace → Uživatelé (V1-AUTH-01). Every handler requires `users.manage` (admin) — also when
 * called directly. No e-mail is sent from here: an invitation / new-password link is generated by
 * Supabase Auth (admin.generateLink, sends nothing) and returned to the admin, who hands it over.
 * Changing one's own role or deactivating oneself is refused; the last active admin is protected by
 * the database (concurrent requests included).
 */
const LINK_VALIDITY_NOTE = "Odkaz je jednorázový a platí omezenou dobu (podle nastavení Supabase Auth, výchozí 24 h). Předejte ho uživateli bezpečnou cestou.";

function errorResponse(error: unknown, fallback: string): NextResponse {
  if (error instanceof LastActiveAdminError) return NextResponse.json({ error: error.message, code: "last_active_admin" }, { status: 409 });
  if (error instanceof UserConflictError) return NextResponse.json({ error: error.message, code: "conflict" }, { status: 409 });
  if (error instanceof AuthGatewayError) return NextResponse.json({ error: error.message, code: error.code }, { status: error.code === "email_exists" ? 409 : 502 });
  if (error instanceof AppBaseUrlError) return NextResponse.json({ error: error.message, code: "config" }, { status: 503 });
  if (error instanceof AuthSchemaNotMigratedError || error instanceof SupabaseConfigurationError) return NextResponse.json({ error: error.message, code: "config" }, { status: 503 });
  console.error(`Users admin: ${fallback}`, error instanceof Error ? error.message : error);
  return NextResponse.json({ error: fallback }, { status: 502 });
}

async function readJson(request: NextRequest): Promise<Record<string, unknown> | undefined> {
  try {
    const body = await request.json();
    return body && typeof body === "object" ? (body as Record<string, unknown>) : undefined;
  } catch {
    return undefined;
  }
}

const displayNameOf = (value: unknown) => (typeof value === "string" && value.trim() ? value.trim().slice(0, 120) : null);
const confirmLink = (base: string, tokenHash: string, type: "invite" | "recovery") => `${base}/auth/confirm?token_hash=${encodeURIComponent(tokenHash)}&type=${type}`;

async function withAuthInfo(users: readonly AdminUserRecord[]) {
  const gateway = authGateway();
  return Promise.all(users.map(async (user) => ({ ...user, auth: await gateway.authUserInfo(user.id).catch(() => undefined) })));
}

export async function handleUsersList(request: NextRequest): Promise<NextResponse> {
  const decision = await authorize(request, "users.manage");
  if (decision.ok === false) return decision.response;
  try {
    const store = usersAdminStore();
    const [users, projects] = await Promise.all([store.list(), store.assignableProjects()]);
    return NextResponse.json({ users: await withAuthInfo(users), projects, currentUserId: decision.auth.user.id });
  } catch (error) {
    return errorResponse(error, "Seznam uživatelů se nepodařilo načíst.");
  }
}

/** Založení účtu + odkaz pozvánky (nic se neodesílá). */
export async function handleUserCreate(request: NextRequest): Promise<NextResponse> {
  const decision = await authorize(request, "users.manage");
  if (decision.ok === false) return decision.response;
  const body = await readJson(request);
  const email = normalizeEmail(body?.email);
  if (!email) return NextResponse.json({ error: "Zadejte platný e-mail." }, { status: 400 });
  if (!isAppRole(body?.role)) return NextResponse.json({ error: "Zvolte roli (Správce / Běžný / Externí)." }, { status: 400 });
  const role = body!.role as AppRole;
  try {
    const base = appBaseUrl(request.url);
    const store = usersAdminStore();
    if ((await store.list()).some((user) => user.email === email)) return NextResponse.json({ error: "Uživatel s tímto e-mailem už existuje.", code: "conflict" }, { status: 409 });
    let link: { userId: string; tokenHash: string; type: "invite" | "recovery" };
    try {
      link = { ...(await authGateway().generateLink("invite", email, `${base}/auth/callback`)), type: "invite" };
    } catch (error) {
      // An Auth account without an app profile (e.g. created earlier): grant access + a set-password link.
      if (!(error instanceof AuthGatewayError) || error.code !== "email_exists") throw error;
      link = { ...(await authGateway().generateLink("recovery", email, `${base}/auth/callback`)), type: "recovery" };
    }
    const user = await store.insert({ id: link.userId, email, displayName: displayNameOf(body?.displayName), role, createdBy: decision.auth.user.id });
    return NextResponse.json({ user, link: confirmLink(base, link.tokenHash, link.type), linkNote: LINK_VALIDITY_NOTE }, { status: 201 });
  } catch (error) {
    return errorResponse(error, "Účet se nepodařilo založit.");
  }
}

/** Role / aktivní stav / jméno. */
export async function handleUserUpdate(request: NextRequest): Promise<NextResponse> {
  const decision = await authorize(request, "users.manage");
  if (decision.ok === false) return decision.response;
  const body = await readJson(request);
  const userId = typeof body?.userId === "string" ? body.userId : "";
  const expectedUpdatedAt = typeof body?.expectedUpdatedAt === "string" ? body.expectedUpdatedAt : "";
  if (!userId || !expectedUpdatedAt) return NextResponse.json({ error: "Chybí uživatel nebo verze záznamu." }, { status: 400 });
  const patch: { role?: AppRole; isActive?: boolean; displayName?: string | null } = {};
  if (body!.role !== undefined) {
    if (!isAppRole(body!.role)) return NextResponse.json({ error: "Neplatná role." }, { status: 400 });
    patch.role = body!.role;
  }
  if (body!.isActive !== undefined) {
    if (typeof body!.isActive !== "boolean") return NextResponse.json({ error: "Neplatný stav účtu." }, { status: 400 });
    patch.isActive = body!.isActive;
  }
  if (body!.displayName !== undefined) patch.displayName = displayNameOf(body!.displayName);
  if (userId === decision.auth.user.id && ((patch.role !== undefined && patch.role !== decision.auth.user.role) || patch.isActive === false)) {
    return NextResponse.json({ error: "Vlastní roli ani vlastní účet nelze změnit tímto způsobem — požádejte jiného správce.", code: "self_change" }, { status: 403 });
  }
  try {
    const user = await usersAdminStore().update(userId, patch, expectedUpdatedAt);
    return NextResponse.json({ user });
  } catch (error) {
    return errorResponse(error, "Změnu účtu se nepodařilo uložit.");
  }
}

/** Nový odkaz: pozvánka (dosud nepřihlášený účet) nebo nastavení nového hesla. Nic se neodesílá. */
export async function handleUserLink(request: NextRequest): Promise<NextResponse> {
  const decision = await authorize(request, "users.manage");
  if (decision.ok === false) return decision.response;
  const body = await readJson(request);
  const userId = typeof body?.userId === "string" ? body.userId : "";
  try {
    const user = await usersAdminStore().get(userId);
    if (!user) return NextResponse.json({ error: "Uživatel neexistuje." }, { status: 404 });
    if (!user.isActive) return NextResponse.json({ error: "Účet je deaktivovaný — nejdřív ho aktivujte." }, { status: 409 });
    const base = appBaseUrl(request.url);
    const info = await authGateway().authUserInfo(user.id);
    const type: "invite" | "recovery" = info?.lastSignInAt ? "recovery" : "invite";
    let link: { tokenHash: string };
    try {
      link = await authGateway().generateLink(type, user.email, `${base}/auth/callback`);
    } catch (error) {
      if (type !== "invite") throw error;
      link = await authGateway().generateLink("recovery", user.email, `${base}/auth/callback`);
    }
    return NextResponse.json({ link: confirmLink(base, link.tokenHash, type === "invite" ? "invite" : "recovery"), kind: type, linkNote: LINK_VALIDITY_NOTE });
  } catch (error) {
    return errorResponse(error, "Odkaz se nepodařilo vytvořit.");
  }
}

/** Přiřazení projektů uživateli (nahradí celé přiřazení). Odebrání platí okamžitě i pro přímá volání API. */
export async function handleUserProjects(request: NextRequest): Promise<NextResponse> {
  const decision = await authorize(request, "users.manage");
  if (decision.ok === false) return decision.response;
  const body = await readJson(request);
  const userId = typeof body?.userId === "string" ? body.userId : "";
  const projectIds = Array.isArray(body?.projectIds) && body!.projectIds.every((id) => typeof id === "string") ? (body!.projectIds as string[]) : undefined;
  if (!userId || !projectIds) return NextResponse.json({ error: "Chybí uživatel nebo seznam projektů." }, { status: 400 });
  try {
    const store = usersAdminStore();
    if (!(await store.get(userId))) return NextResponse.json({ error: "Uživatel neexistuje." }, { status: 404 });
    return NextResponse.json({ projectIds: await store.setProjects(userId, projectIds, decision.auth.user.id) });
  } catch (error) {
    return errorResponse(error, "Přiřazení projektů se nepodařilo uložit.");
  }
}
